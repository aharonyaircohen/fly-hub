import { beforeEach, describe, expect, it, vi } from "vitest";

// Variables now live in Convex (repoDocs kind "variables") — mock the client.
const convex = vi.hoisted(() => ({
  query: vi.fn(),
  mutation: vi.fn(),
}));
const vault = vi.hoisted(() => ({
  read: vi.fn(),
  upsert: vi.fn(),
}));
const webhooks = vi.hoisted(() => ({
  ensureWebhook: vi.fn(),
}));

vi.mock("convex/browser", () => ({
  ConvexHttpClient: class {
    query = convex.query;
    mutation = convex.mutation;
  },
}));
vi.mock("@kody-ade/base/vault/store", () => ({
  readVault: vault.read,
}));
vi.mock("@kody-ade/base/vault/mutations", () => ({
  upsertSecret: vault.upsert,
}));
vi.mock("@dashboard/lib/webhooks/register", () => webhooks);

import { _resetConvexClient } from "@kody-ade/base/backend/convex";
import { invalidateVariablesCache } from "@kody-ade/base/variables/store";
import {
  installEngine,
  WORKFLOW_TEMPLATE_SOURCE,
  type InstallEngineInput,
} from "@dashboard/lib/engine/install";

const KODY_WORKFLOW = `# Generated by @kody-ade/kody-engine.
name: kody
requestId:
sessionId:
message:
dashboardUrl:
DASHBOARD_URL:
permissions:
  id-token: write
token: \${{ secrets.GH_PAT || secrets.KODY_TOKEN || github.token }}
run: npx -y -p @kody-ade/kody-engine@latest kody-engine
`;

/** Seed the Convex variables doc returned by repoDocs:get. */
function mockVariables(models: Array<Record<string, unknown>>) {
  convex.query.mockResolvedValue({
    doc: {
      version: 1,
      variables: {
        LLM_MODELS: {
          value: JSON.stringify(models),
          updatedAt: "2026-01-01T00:00:00.000Z",
        },
      },
    },
    updatedAt: "2026-01-01T00:00:00.000Z",
  });
}

beforeEach(() => {
  vi.clearAllMocks();
  _resetConvexClient();
  process.env.CONVEX_URL = "https://example.convex.cloud";
  invalidateVariablesCache("example", "my-repo");
  convex.query.mockResolvedValue(null); // no variables doc by default
  vault.read.mockResolvedValue({
    doc: { version: 1, secrets: {} },
    sha: null,
  });
  vault.upsert.mockResolvedValue({ secrets: [] });
  webhooks.ensureWebhook.mockResolvedValue({
    ok: true,
    created: false,
    hookId: 42,
  });
  vi.stubGlobal(
    "fetch",
    vi
      .fn()
      .mockResolvedValue(
        new Response(KODY_WORKFLOW, { status: 200, statusText: "OK" }),
      ),
  );
});

